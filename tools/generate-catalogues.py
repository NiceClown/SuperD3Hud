#!/usr/bin/env python3
"""Generates host implementations for the large TurboHUD list interfaces.

The plugin API declares thousands of properties, one per game entity:
`ISnoItem Unique_Sword_1H_001 { get; }` and so on. Writing them by hand is
pointless, so this script parses the interface files and emits a class where
every property is resolved lazily by name at run time.

Only the huge "catalogue" interfaces are generated:
  ISnoItemList, ISnoPowerList, ISnoQuestList, IAttributeList, ISnoActorList
The small hand-written controllers live in the normal source tree.
"""
import io
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
IFACE = os.path.join(ROOT, "compat", "interfaces")
OUT = os.path.join(ROOT, "src", "turbohost", "HostCatalogues.g.cs")
OUT_NAMES = os.path.join(ROOT, "src", "turbohost", "HostNames.g.cs")

# interface name -> (file, element type, lookup method on the resolver)
TARGETS = [
    ("ISnoItemList", "controllers/sno/ISnoItemList.cs", "ISnoItem", "SnoItem"),
    ("ISnoPowerList", "controllers/sno/ISnoPowerList.cs", "ISnoPower", "SnoPower"),
    ("ISnoQuestList", "controllers/sno/ISnoQuestList.cs", "ISnoQuest", "SnoQuest"),
    ("IAttributeList", "controllers/sno/IAttributeList.cs", "IAttribute", "Attribute"),
    ("ISnoActorList", "controllers/sno/ISnoActorList.cs", "ISnoActor", "SnoActor"),
]

PROP = re.compile(r"^[ \t]*([A-Za-z_][A-Za-z0-9_\.<>\[\]]*)[ \t]+([A-Za-z_][A-Za-z0-9_]*)[ \t]*\{[ \t]*get[ \t]*;[ \t]*\}[ \t]*;?", re.M)


def parse(path):
    """Returns [(type, name, sno, display)] for every read-only property."""
    text = io.open(path, encoding="utf-8-sig").read()
    props = []
    for match in PROP.finditer(text):
        type_name = match.group(1)
        name = match.group(2)
        # A trailing comment may carry the SNO: "// 12345 - Some Name"
        line_end = text.find("\n", match.end())
        comment = text[match.end():line_end] if line_end > 0 else ""
        sno = 0
        sno_match = re.search(r"//\s*(\d+)", comment)
        if sno_match:
            sno = int(sno_match.group(1))
        display = ""
        tail = re.search(r"//\s*\d+\s*-\s*(.+)$", comment)
        if tail:
            display = tail.group(1).strip()
        props.append((type_name, name, sno, display))
    return props


def main():
    lines = []
    lines.append("// <auto-generated>")
    lines.append("//   Generated by tools/generate-catalogues.py from the public plugin API.")
    lines.append("//   Do not edit by hand: change the generator instead.")
    lines.append("// </auto-generated>")
    lines.append("using System.Collections.Generic;")
    lines.append("using Turbo.Plugins;")
    lines.append("")
    lines.append("namespace SuperD3Hud.TurboHost")
    lines.append("{")
    lines.append("    /// <summary>")
    lines.append("    /// Resolves catalogue entries by name or SNO. Implemented by the host,")
    lines.append("    /// so the generated classes stay free of game logic.")
    lines.append("    /// </summary>")
    lines.append("    public interface ICatalogueResolver")
    lines.append("    {")
    lines.append("        ISnoItem SnoItem(string code, uint sno);")
    lines.append("        ISnoPower SnoPower(string code, uint sno);")
    lines.append("        ISnoQuest SnoQuest(string code, uint sno);")
    lines.append("        IAttribute Attribute(string code, uint index);")
    lines.append("        ISnoActor SnoActor(string code, uint sno);")
    lines.append("        IEnumerable<ISnoItem> AllSnoItems { get; }")
    lines.append("        IEnumerable<ISnoPower> AllSnoPowers { get; }")
    lines.append("        IEnumerable<ISnoQuest> AllSnoQuests { get; }")
    lines.append("    }")
    lines.append("")

    total = 0
    for iface, rel, element, method in TARGETS:
        path = os.path.join(IFACE, rel)
        if not os.path.exists(path):
            sys.stderr.write("skip (missing): " + rel + "\n")
            continue

        props = parse(path)
        # Only keep properties whose type matches the element type.
        props = [p for p in props if p[0].split(".")[-1] == element]
        total += len(props)

        lines.append("    /// <summary>Generated implementation of " + iface + ".</summary>")
        lines.append("    public partial class Host" + iface[1:] + " : " + iface)
        lines.append("    {")
        lines.append("        private readonly ICatalogueResolver _resolver;")
        lines.append("")
        lines.append("        public Host" + iface[1:] + "(ICatalogueResolver resolver)")
        lines.append("        {")
        lines.append("            _resolver = resolver;")
        lines.append("        }")
        lines.append("")

        for type_name, name, sno, _display in props:
            lines.append("        public " + element + " " + name)
            lines.append("        {")
            lines.append('            get { return _resolver.' + method +
                         '("' + name + '", ' + str(sno) + "u); }")
            lines.append("        }")

        lines.append("    }")
        lines.append("")

    lines.append("}")

    text = "\n".join(lines) + "\n"
    io.open(OUT, "w", encoding="utf-8", newline="").write(text)
    print("generated", OUT, "properties:", total)

    write_names()


def prettify(identifier):
    """Turns a code identifier into a readable label.

    The public API carries a readable name in a comment for most items, but
    powers often have only an identifier such as "DemonHunter_Passive_SteadyAim".
    Splitting it gives a usable label without inventing anything.
    """
    parts = [p for p in identifier.split("_") if p]
    cleaned = []
    for part in parts:
        lowered = part.lower()
        # Bookkeeping words that carry no meaning for a player.
        if lowered in ("generic", "unique", "x1",
                       "p1", "p2", "p3", "p4", "ptr", "test", "dev", "dummy"):
            continue
        cleaned.append(part)
    if not cleaned:
        cleaned = parts

    words = []
    for part in cleaned:
        current = []
        previous = ""
        for ch in part:
            if ch.isupper() and previous and previous.islower():
                words.append("".join(current))
                current = [ch]
            else:
                current.append(ch)
            previous = ch
        if current:
            words.append("".join(current))
    return " ".join(words)


def write_names():
    """Emits readable names of powers and items from the same sources."""
    powers = parse(os.path.join(IFACE, "controllers", "sno", "ISnoPowerList.cs"))
    items = parse(os.path.join(IFACE, "controllers", "sno", "ISnoItemList.cs"))

    lines = []
    lines.append("// <auto-generated>")
    lines.append("//   Generated by tools/generate-catalogues.py from the public plugin API.")
    lines.append("//   Do not edit by hand: change the generator instead.")
    lines.append("// </auto-generated>")
    lines.append("using System.Collections.Generic;")
    lines.append("")
    lines.append("namespace SuperD3Hud.TurboHost")
    lines.append("{")
    lines.append("    /// <summary>")
    lines.append("    /// Readable names of powers and items, taken from the identifiers and")
    lines.append("    /// comments of the public plugin API. They are only labels: a missing")
    lines.append("    /// name never hides an entity.")
    lines.append("    /// </summary>")
    lines.append("    public static class HostNames")
    lines.append("    {")

    for dict_name, props in (("PowerName", powers), ("ItemName", items)):
        field = "_" + dict_name[0].lower() + dict_name[1:]
        code_field = field + "Code"
        lines.append("        private static Dictionary<uint, string> " + field + ";")
        lines.append("        private static Dictionary<uint, string> " + code_field + ";")
        lines.append("")
        lines.append("        private static Dictionary<uint, string> Build" + dict_name + "()")
        lines.append("        {")
        lines.append("            Dictionary<uint, string> map = new Dictionary<uint, string>();")
        seen = set()
        for _type, name, sno, display in props:
            if sno == 0 or sno in seen:
                continue
            seen.add(sno)
            # A comment may repeat the identifier ("// 318801 -
            # ItemPassive_Unique_Ring_619_x1"); such a label is no better than
            # the identifier itself, so both are prettified the same way.
            if display and "_" not in display:
                label = display
            else:
                label = prettify(display if display else name)
            label = label.replace("\\", "\\\\").replace('"', '\\"')
            lines.append('            map[' + str(sno) + 'u] = "' + label + '";')
        lines.append("            return map;")
        lines.append("        }")
        lines.append("")
        lines.append("        private static Dictionary<uint, string> Build" + dict_name + "Code()")
        lines.append("        {")
        lines.append("            Dictionary<uint, string> map = new Dictionary<uint, string>();")
        seen = set()
        for _type, name, sno, display in props:
            if sno == 0 or sno in seen:
                continue
            seen.add(sno)
            # The comment often carries the real game identifier even when the
            # property has a friendly name ("HomingPads" -> the comment says
            # "ItemPassive_Unique_Ring_619_x1"). Prefer that identifier.
            raw = display if (display and "_" in display) else name
            raw = raw.replace("\\", "\\\\").replace('"', '\\"')
            lines.append('            map[' + str(sno) + 'u] = "' + raw + '";')
        lines.append("            return map;")
        lines.append("        }")
        lines.append("")
        lines.append("        /// <summary>Readable name of the entry, or an empty string.</summary>")
        lines.append("        public static string " + dict_name + "(uint sno)")
        lines.append("        {")
        lines.append("            if (" + field + " == null) " + field +
                     " = Build" + dict_name + "();")
        lines.append("            string name;")
        lines.append("            return " + field + ".TryGetValue(sno, out name) ? name : \"\";")
        lines.append("        }")
        lines.append("")
        lines.append("        /// <summary>Original identifier of the entry, or an empty string.</summary>")
        lines.append("        public static string " + dict_name + "Code(uint sno)")
        lines.append("        {")
        lines.append("            if (" + code_field + " == null) " + code_field +
                     " = Build" + dict_name + "Code();")
        lines.append("            string name;")
        lines.append("            return " + code_field + ".TryGetValue(sno, out name) ? name : \"\";")
        lines.append("        }")
        lines.append("")

    lines.append("    }")
    lines.append("}")

    io.open(OUT_NAMES, "w", encoding="utf-8", newline="").write("\n".join(lines) + "\n")
    print("generated", OUT_NAMES, "powers:", len(powers), "items:", len(items))


if __name__ == "__main__":
    main()
